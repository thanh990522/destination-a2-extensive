#!/usr/bin/env python3
"""Collect every emoji used in the course data and scripts, then fetch the matching
Microsoft Fluent Emoji 3D image (MIT licence) and save it as a small WebP file.

Usage (from the repository root, needs git, Pillow and the 'emoji' package):
    python3 tools/icons.py /path/to/fluentui-emoji-checkout

The checkout can be a sparse, blob-less clone:
    git clone --filter=blob:none --no-checkout --depth 1 https://github.com/microsoft/fluentui-emoji fe
The script asks git for only the files it needs. Emoji without a Fluent image keep
their normal text form in the browser.
"""
import glob, json, os, subprocess, sys
import emoji
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'assets', 'icons')
SIZE = 256
norm = lambda e: '-'.join('%x' % ord(c) for c in e if ord(c) != 0xFE0F)

def main(fe):
    subprocess.run(['git', '-C', fe, 'sparse-checkout', 'init', '--no-cone'], check=True)
    sparse = os.path.join(fe, '.git', 'info', 'sparse-checkout')
    with open(sparse, 'w') as f: f.write('assets/*/metadata.json\n')
    subprocess.run(['git', '-C', fe, 'checkout'], check=True, capture_output=True)
    table = {}
    for m in glob.glob(os.path.join(fe, 'assets', '*', 'metadata.json')):
        d = json.load(open(m, encoding='utf-8')); table[norm(d['glyph'])] = os.path.dirname(m)
    used = set()
    files = glob.glob(os.path.join(ROOT, 'assets', 'data', '**', '*.js'), recursive=True) + glob.glob(os.path.join(ROOT, 'assets', 'js', '*.js'))
    for f in files:
        for m in emoji.emoji_list(open(f, encoding='utf-8').read()): used.add(m['emoji'])
    wanted, paths = {}, []
    for e in sorted(used):
        folder = table.get(norm(e))
        if not folder: print('no Fluent image:', e); continue
        rel = os.path.relpath(folder, fe)
        cand = [os.path.join(rel, '3D'), os.path.join(rel, 'Default', '3D')]
        wanted[norm(e)] = cand; paths += [c + '/*' for c in cand]
    with open(sparse, 'a') as f: f.write('\n'.join(p.replace(' ', '\\ ') for p in paths) + '\n')
    subprocess.run(['git', '-C', fe, 'checkout'], check=True, capture_output=True)
    os.makedirs(OUT, exist_ok=True)
    mapping = {}
    for key, cand in wanted.items():
        src = None
        for c in cand:
            pngs = glob.glob(os.path.join(fe, c, '*.png'))
            if pngs: src = pngs[0]; break
        if not src: print('missing file for', key); continue
        im = Image.open(src).convert('RGBA'); im.thumbnail((SIZE, SIZE), Image.LANCZOS)
        name = key + '.webp'; im.save(os.path.join(OUT, name), 'WEBP', quality=82, method=6)
        mapping[key] = name
    with open(os.path.join(OUT, 'icons.js'), 'w', encoding='utf-8') as f:
        f.write('/* Fluent Emoji 3D (Microsoft, MIT licence), resized to WebP. Generated by tools/icons.py. */\n')
        f.write('window.A2_ICONS = ' + json.dumps(mapping, separators=(',', ':')) + ';\n')
    print(len(mapping), 'icons written')

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'fe')
